int main () {

    int x = 10;
    int y = 3;


    cout << (x + y) << "\n"; // 13
    cout << (x - y) << "\n"; // 7
    cout << (x * y) << "\n"; // 30
    cout << (x / y) << "\n"; // 3 (integer division)
    cout << (x % y) << "\n"; // 1

    int z = 5;
    ++z;                    // Increment, increase value
    cout << z << "\n"; 
    --z; --z;                    // Decrement, decrease value
    cout << z << "\n";


return 0;
}









